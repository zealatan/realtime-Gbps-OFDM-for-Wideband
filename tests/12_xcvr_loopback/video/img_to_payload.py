#!/usr/bin/env python3
"""
img_to_payload.py -- pack an image into N OFDM DMA-TX payload frames.

Each frame carries 10608 payload bits = 1326 bytes (2652 16-QAM carriers x 4
bits), LSB-first, matching the on-chip packing flat4[w*32+i]=word[w] bit i.
A WxH grayscale image (W*H bytes) is split into N = ceil(W*H/1326) frames; the
firmware sends each as a clean single-frame loopback (per-frame transceiver
soft-reset) at BER=0 and the host reassembles the full image.

Emits tx_image_words.h (NFRAMES x 332 u32) + saves the original PNG.
"""
import os
import numpy as np
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 104, 102                  # 104*102 = 10608 bytes = exactly 8 frames
NBYTES = W * H
FRAME_BYTES = 1326
FRAME_WORDS = 332
NFRAMES = (NBYTES + FRAME_BYTES - 1) // FRAME_BYTES
UPSCALE = 5


def make_test_image():
    """A detailed, clearly-recognizable grayscale image so any bit error is
    visually obvious: gradient bg, shapes, gridlines, big text."""
    img = Image.new("L", (W, H), 0)
    px = img.load()
    for y in range(H):
        for x in range(W):
            px[x, y] = (x * 255 // (W - 1) + (H - 1 - y) * 255 // (H - 1)) // 2
    d = ImageDraw.Draw(img)
    d.rectangle([0, 0, W - 1, H - 1], outline=255)
    for gx in range(0, W, 13):
        d.line([gx, 0, gx, H - 1], fill=90)
    for gy in range(0, H, 13):
        d.line([0, gy, W - 1, gy], fill=90)
    d.ellipse([10, 12, 48, 50], outline=255, fill=30)
    d.ellipse([20, 22, 38, 40], outline=0, fill=220)
    d.rectangle([58, 14, 96, 48], outline=0, fill=200)
    d.line([58, 14, 96, 48], fill=0)
    d.line([96, 14, 58, 48], fill=0)
    d.text((8, 60), "ZCU216", fill=255)
    d.text((8, 72), "OFDM", fill=0)
    d.text((8, 84), "DMA-TX", fill=255)
    return img


def prbs_bits(n, seed=0xACE1):
    """Deterministic PRBS (x^16+x^14+x^13+x^11+1) whitening sequence, so no
    payload frame has a pathological high-PAPR OFDM symbol that saturates the
    fixed-point PHY. The reconstructor XORs the same sequence back out."""
    lfsr = seed & 0xFFFF
    out = np.zeros(n, dtype=np.uint8)
    for i in range(n):
        bit = lfsr & 1
        out[i] = bit
        lfsr >>= 1
        if bit:
            lfsr ^= 0xB400
    return out


SCRAMBLE = prbs_bits(10608)


def pack_frames(img):
    b = np.asarray(img, dtype=np.uint8).reshape(-1)
    assert b.size == NBYTES
    buf = np.zeros(NFRAMES * FRAME_BYTES, dtype=np.uint8)
    buf[:NBYTES] = b                                   # pad last frame with 0
    words = np.zeros((NFRAMES, FRAME_WORDS), dtype=np.uint32)
    for f in range(NFRAMES):
        fb = buf[f * FRAME_BYTES:(f + 1) * FRAME_BYTES]
        bits = np.unpackbits(fb, bitorder="little") ^ SCRAMBLE   # 10608 bits, whitened
        for w in range(FRAME_WORDS):
            acc = 0
            for k in range(32):
                j = w * 32 + k
                if j < bits.size and bits[j]:
                    acc |= (1 << k)
            words[f, w] = acc
    return words


def emit_header(words, path):
    with open(path, "w") as f:
        f.write("/* AUTO-GENERATED by img_to_payload.py -- image as N OFDM\n")
        f.write(" * payload frames (LSB-first, matches rom_flat4). */\n")
        f.write("#ifndef TX_IMAGE_WORDS_H\n#define TX_IMAGE_WORDS_H\n")
        f.write(f"#define TX_IMAGE_W {W}\n#define TX_IMAGE_H {H}\n")
        f.write(f"#define TX_IMAGE_NFRAMES {NFRAMES}\n")
        f.write(f"static const u32 tx_image_words[{NFRAMES}][{FRAME_WORDS}] = {{\n")
        for fr in range(NFRAMES):
            f.write("  {\n")
            for i in range(0, FRAME_WORDS, 8):
                row = ", ".join(f"0x{int(w):08X}U" for w in words[fr, i:i + 8])
                f.write(f"    {row},\n")
            f.write("  },\n")
        f.write("};\n#endif\n")


def main():
    img = make_test_image()
    words = pack_frames(img)
    hdr = os.path.normpath(os.path.join(
        HERE, "..", "..", "..", "software", "generated", "rfdc_capture_ws",
        "rfdc_capture", "src", "tx_image_words.h"))
    emit_header(words, hdr)
    img.resize((W * UPSCALE, H * UPSCALE), Image.NEAREST).save(
        os.path.join(HERE, "image_orig.png"))
    np.asarray(img, dtype=np.uint8).tofile(os.path.join(HERE, "image_orig.raw"))
    print(f"image {W}x{H} = {NBYTES} bytes -> {NFRAMES} frames")
    print(f"wrote header  -> {hdr}")
    print(f"wrote original-> {os.path.join(HERE, 'image_orig.png')}")


if __name__ == "__main__":
    main()
