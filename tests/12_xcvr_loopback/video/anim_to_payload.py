#!/usr/bin/env python3
"""
anim_to_payload.py -- generate a short animation and pack each frame as ONE OFDM
DMA-TX payload frame (39x34 grayscale = 1326 bytes = 10608 bits). The firmware
streams the NFRAMES frames back-to-back (per-frame transceiver soft-reset) and
the host reassembles them into a recovered animated GIF -> a video over OFDM.

LSB-first packing (flat4[w*32+i]=word[w] bit i) + PRBS whitening, same as the
still-image path. Emits tx_image_words[NFRAMES][332] and saves the original GIF.
"""
import os
import numpy as np
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
W, H = 39, 34                    # 39*34 = 1326 bytes = one payload frame
NFRAMES = 16
FRAME_BYTES = 1326
FRAME_WORDS = 332
UPSCALE = 8


def prbs_bits(n, seed=0xACE1):
    lfsr = seed & 0xFFFF
    out = np.zeros(n, dtype=np.uint8)
    for i in range(n):
        bit = lfsr & 1
        out[i] = bit
        lfsr >>= 1
        if bit:
            lfsr ^= 0xB400
    return out


SCRAMBLE = prbs_bits(10608)


def make_animation():
    """NFRAMES of a bouncing ball + moving bar + frame counter on a gradient."""
    frames = []
    for f in range(NFRAMES):
        img = Image.new("L", (W, H), 0)
        px = img.load()
        for y in range(H):
            for x in range(W):
                px[x, y] = (x * 200 // (W - 1)) // 2 + 20
        d = ImageDraw.Draw(img)
        d.rectangle([0, 0, W - 1, H - 1], outline=255)
        # bouncing ball (triangle wave path)
        t = f / (NFRAMES - 1)
        bx = 5 + int((W - 16) * abs(2 * (t - 0.5)))
        by = 6 + int((H - 20) * abs(2 * ((t * 2) % 1.0 - 0.5)))
        d.ellipse([bx, by, bx + 8, by + 8], fill=255, outline=0)
        # sweeping vertical bar
        sx = 2 + (f * (W - 4)) // NFRAMES
        d.line([sx, 2, sx, H - 3], fill=0)
        # frame counter
        d.text((3, H - 10), "f%02d" % f, fill=255)
        frames.append(img)
    return frames


def pack_frame(img):
    b = np.asarray(img, dtype=np.uint8).reshape(-1)
    assert b.size == FRAME_BYTES
    bits = np.unpackbits(b, bitorder="little") ^ SCRAMBLE
    words = np.zeros(FRAME_WORDS, dtype=np.uint32)
    for w in range(FRAME_WORDS):
        acc = 0
        for k in range(32):
            j = w * 32 + k
            if j < bits.size and bits[j]:
                acc |= (1 << k)
        words[w] = acc
    return words


def emit_header(all_words, path):
    with open(path, "w") as fp:
        fp.write("/* AUTO-GENERATED by anim_to_payload.py -- animation frames as\n")
        fp.write(" * OFDM payload frames (LSB-first + PRBS, one frame per image). */\n")
        fp.write("#ifndef TX_IMAGE_WORDS_H\n#define TX_IMAGE_WORDS_H\n")
        fp.write(f"#define TX_IMAGE_W {W}\n#define TX_IMAGE_H {H}\n")
        fp.write(f"#define TX_IMAGE_NFRAMES {NFRAMES}\n")
        fp.write(f"static const u32 tx_image_words[{NFRAMES}][{FRAME_WORDS}] = {{\n")
        for fr in range(NFRAMES):
            fp.write("  {\n")
            for i in range(0, FRAME_WORDS, 8):
                row = ", ".join(f"0x{int(w):08X}U" for w in all_words[fr][i:i + 8])
                fp.write(f"    {row},\n")
            fp.write("  },\n")
        fp.write("};\n#endif\n")


def main():
    frames = make_animation()
    all_words = [pack_frame(im) for im in frames]
    hdr = os.path.normpath(os.path.join(
        HERE, "..", "..", "..", "software", "generated", "rfdc_capture_ws",
        "rfdc_capture", "src", "tx_image_words.h"))
    emit_header(all_words, hdr)
    up = [im.resize((W * UPSCALE, H * UPSCALE), Image.NEAREST) for im in frames]
    up[0].save(os.path.join(HERE, "anim_orig.gif"), save_all=True,
               append_images=up[1:], duration=120, loop=0)
    np.stack([np.asarray(im, np.uint8) for im in frames]).tofile(
        os.path.join(HERE, "anim_orig.raw"))
    print(f"animation {W}x{H} x {NFRAMES} frames -> {hdr}")
    print(f"original GIF -> {os.path.join(HERE, 'anim_orig.gif')}")


if __name__ == "__main__":
    main()
