#!/usr/bin/env python3
"""
vid_to_payload.py -- pack a REAL COLOR video clip into OFDM DMA-TX payload frames.

Extracts NVFRAMES evenly-spaced frames from a source clip (ffmpeg), scales to
VW x VH RGB (VW*VH*3 = FPP*1326 bytes = FPP payload frames per video frame), and
packs the RGB bytes LSB-first + PRBS-whitened into tx_image_words[NVFRAMES*FPP][332].
The firmware streams all payload frames; the host reassembles the color clip.
"""
import os
import subprocess
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(ROOT, "FPGA_TOP", "FPGA_RESULT_VIDEO.mp4")
VW, VH = 51, 26                  # 51*26*3 = 3978 bytes = exactly 3 payload frames
NVFRAMES = 16
FPP = (VW * VH * 3) // 1326      # payload frames per video frame (=3)
NFRAMES = NVFRAMES * FPP         # total payload frames (=48)
FRAME_BYTES = 1326
FRAME_WORDS = 332
UPSCALE = 8


def prbs_bits(n, seed=0xACE1):
    lfsr = seed & 0xFFFF
    out = np.zeros(n, dtype=np.uint8)
    for i in range(n):
        bit = lfsr & 1
        out[i] = bit
        lfsr >>= 1
        if bit:
            lfsr ^= 0xB400
    return out


SCRAMBLE = prbs_bits(10608)


def extract_frames():
    fdir = os.path.join(HERE, "frames")
    os.makedirs(fdir, exist_ok=True)
    for f in os.listdir(fdir):
        os.remove(os.path.join(fdir, f))
    step = 47                    # ~759/16
    subprocess.run(
        ["ffmpeg", "-v", "error", "-i", SRC,
         "-vf", f"select='not(mod(n\\,{step}))',scale={VW}:{VH}:flags=lanczos",
         "-vsync", "0", "-frames:v", str(NVFRAMES), "-start_number", "0",
         os.path.join(fdir, "f%02d.png")], check=True)
    imgs = []
    for i in range(NVFRAMES):
        p = os.path.join(fdir, f"f{i:02d}.png")
        imgs.append(np.asarray(Image.open(p).convert("RGB"), dtype=np.uint8))
    return imgs                  # list of (VH,VW,3)


def pack_bytes_to_words(fb):
    bits = np.unpackbits(fb, bitorder="little") ^ SCRAMBLE
    words = np.zeros(FRAME_WORDS, dtype=np.uint32)
    for w in range(FRAME_WORDS):
        acc = 0
        for k in range(32):
            j = w * 32 + k
            if j < bits.size and bits[j]:
                acc |= (1 << k)
        words[w] = acc
    return words


def emit_header(all_words, path):
    with open(path, "w") as fp:
        fp.write("/* AUTO-GENERATED by vid_to_payload.py -- COLOR video clip as\n")
        fp.write(" * OFDM payload frames (RGB, LSB-first + PRBS whitened). */\n")
        fp.write("#ifndef TX_IMAGE_WORDS_H\n#define TX_IMAGE_WORDS_H\n")
        fp.write(f"#define TX_IMAGE_W {VW}\n#define TX_IMAGE_H {VH}\n")
        fp.write(f"#define TX_IMAGE_NFRAMES {NFRAMES}\n")
        fp.write(f"static const u32 tx_image_words[{NFRAMES}][{FRAME_WORDS}] = {{\n")
        for fr in range(NFRAMES):
            fp.write("  {\n")
            for i in range(0, FRAME_WORDS, 8):
                row = ", ".join(f"0x{int(w):08X}U" for w in all_words[fr][i:i + 8])
                fp.write(f"    {row},\n")
            fp.write("  },\n")
        fp.write("};\n#endif\n")


def main():
    imgs = extract_frames()
    all_words = []
    for im in imgs:                          # each video frame -> FPP payload frames
        raw = im.reshape(-1)                  # VH*VW*3 bytes, RGB interleaved
        for k in range(FPP):
            all_words.append(pack_bytes_to_words(raw[k * FRAME_BYTES:(k + 1) * FRAME_BYTES]))
    hdr = os.path.normpath(os.path.join(
        ROOT, "software", "generated", "rfdc_capture_ws",
        "rfdc_capture", "src", "tx_image_words.h"))
    emit_header(all_words, hdr)
    up = [Image.fromarray(im).resize((VW * UPSCALE, VH * UPSCALE), Image.NEAREST)
          for im in imgs]
    up[0].save(os.path.join(HERE, "vid_orig.gif"), save_all=True,
               append_images=up[1:], duration=120, loop=0)
    np.stack(imgs).tofile(os.path.join(HERE, "vid_orig.raw"))
    print(f"color video {VW}x{VH} RGB x {NVFRAMES} frames "
          f"= {NFRAMES} payload frames ({FPP}/vframe) -> {hdr}")
    print(f"original GIF -> {os.path.join(HERE, 'vid_orig.gif')}")


if __name__ == "__main__":
    main()
