#!/usr/bin/env bash
# run_p3_11_real_fft_meyr_dryrun_xsim.sh — P3-11 real FFT / Meyr dry-run pre-flight check
#
# This script checks file existence and reports BLOCKED for any missing dependency.
# It does NOT run simulation. It does NOT fake a PASS.
#
# Usage:
#   bash scripts/run_p3_11_real_fft_meyr_dryrun_xsim.sh
#
# Exit codes:
#   0 = all checks passed (ready to proceed to P3-12 simulation)
#   1 = one or more BLOCKED conditions found
#
# DO NOT modify to bypass any BLOCKED check.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_ROOT"

BLOCKED=0

echo "=========================================="
echo "P3-11 Real FFT / Meyr Path — Dry-run Pre-flight"
echo "  Date       : $(date '+%Y-%m-%d %H:%M')"
echo "  Project    : $PROJECT_ROOT"
echo "=========================================="

# ---------------------------------------------------------------------------
# Helper functions
# ---------------------------------------------------------------------------
check_file() {
    local label="$1"
    local path="$2"
    if [[ -f "$path" ]]; then
        echo "  [OK]      $label"
        echo "            $path"
    else
        echo "  [BLOCKED] $label"
        echo "            MISSING: $path"
        BLOCKED=1
    fi
}

check_tool() {
    local label="$1"
    local cmd="$2"
    local ver_flag="${3:--V}"
    if command -v "$cmd" &>/dev/null; then
        local ver
        ver="$(${cmd} ${ver_flag} 2>&1 | head -1 || true)"
        echo "  [OK]      $label: $ver"
    else
        echo "  [BLOCKED] $label: '$cmd' not found on PATH"
        BLOCKED=1
    fi
}

check_dir() {
    local label="$1"
    local path="$2"
    if [[ -d "$path" ]]; then
        echo "  [OK]      $label"
        echo "            $path"
    else
        echo "  [BLOCKED] $label"
        echo "            MISSING directory: $path"
        BLOCKED=1
    fi
}

# ---------------------------------------------------------------------------
# Section 1: P3-08 Baseline
# ---------------------------------------------------------------------------
echo ""
echo "--- Section 1: P3-08 Baseline Sentinel ---"
check_file "P3-08 sentinel (meyr_reference_debug.json)" \
    "golden/meyr_reference_debug.json"
check_file "Bypass-compatible PSS ROM" \
    "vectors/meyr_pss_reference_romhex.txt"
check_file "Bypass-compatible SSS ROM" \
    "vectors/meyr_sss_reference_romhex.txt"

# ---------------------------------------------------------------------------
# Section 2: RTL Sources (must NOT be modified)
# ---------------------------------------------------------------------------
echo ""
echo "--- Section 2: Required RTL (read-only) ---"
check_file "meyr_fft256_actual_integration_top.v" \
    "rtl/meyr_fft256_actual_integration_top.v"
check_file "fft256_xilinx_wrapper.v" \
    "rtl/fft256_xilinx_wrapper.v"
check_file "meyr_integer_cfo_freq_estimator_top.v" \
    "rtl/meyr_integer_cfo_freq_estimator_top.v"
check_file "meyr_integer_cfo_core.v" \
    "rtl/meyr_integer_cfo_core.v"
check_file "meyr_pss_sss_product_gen.v" \
    "rtl/meyr_pss_sss_product_gen.v"
check_file "peak_detector.v" \
    "rtl/peak_detector.v"

# ---------------------------------------------------------------------------
# Section 3: P3-12 Artifacts (must be CREATED by P3-12 session)
# ---------------------------------------------------------------------------
echo ""
echo "--- Section 3: P3-12 Deliverables (created by P3-12 session) ---"

check_file "Frequency-domain ROM generator script" \
    "scripts/gen_meyr_fft_reference_roms.py"
check_file "FFT-compatible PSS ROM" \
    "vectors/meyr_pss_fft_romhex.txt"
check_file "FFT-compatible SSS ROM" \
    "vectors/meyr_sss_fft_romhex.txt"
check_file "Interface adapter RTL" \
    "rtl/meyr_fft256_harness_adapter.v"
check_file "P3-11 standalone testbench" \
    "tb/p3_11_real_fft_meyr_tb.sv"

# ---------------------------------------------------------------------------
# Section 4: Sweep Vectors (generated by P3-09)
# ---------------------------------------------------------------------------
echo ""
echo "--- Section 4: Sweep Vectors (P3-09) ---"
check_file "Sweep manifest" \
    "golden/p3_09_sweep/manifest.json"
for tag in km8 km4 km2 km1 k0 kp1 kp2 kp4 kp8; do
    check_file "Sweep vector case_${tag}.mem" \
        "golden/p3_09_sweep/case_${tag}.mem"
done

# ---------------------------------------------------------------------------
# Section 5: Simulators
# ---------------------------------------------------------------------------
echo ""
echo "--- Section 5: Simulator Availability ---"
check_tool "iverilog" "iverilog" "-V"

echo ""
echo "  [INFO] Checking xsim / Vivado..."
if command -v xsim &>/dev/null; then
    ver="$(xsim --version 2>&1 | head -1 || true)"
    echo "  [OK]      xsim: $ver"
else
    echo "  [BLOCKED] xsim: not found on PATH"
    echo "            xsim is required for USE_BEHAVIORAL_STUB=0 (accurate CFO simulation)"
    echo "            Install Vivado 2023.x and source settings64.sh to resolve."
    BLOCKED=1
fi

if command -v vivado &>/dev/null; then
    ver="$(vivado -version 2>&1 | head -1 || true)"
    echo "  [OK]      vivado: $ver"
else
    echo "  [BLOCKED] vivado: not found on PATH"
    echo "            Vivado is required to generate fft256_xilinx IP and run xsim."
    BLOCKED=1
fi

# ---------------------------------------------------------------------------
# Section 6: Xilinx FFT IP
# ---------------------------------------------------------------------------
echo ""
echo "--- Section 6: Xilinx FFT IP Dependencies ---"
check_dir  "ip/ directory" "ip"
check_file "fft256_xilinx XCI config" \
    "ip/fft256_xilinx/fft256_xilinx/fft256_xilinx.xci"
check_file "fft256_xilinx simulation netlist (.v or .veo)" \
    "ip/fft256_xilinx/fft256_xilinx/fft256_xilinx.veo"

echo ""
echo "--- Section 7: Bypass guard check (P3-08 bypass stub still active) ---"
FFT_BYPASS_SRC="rtl/unit_test/fft256_dual_symbol_frontend.v"
if [[ -f "$FFT_BYPASS_SRC" ]]; then
    if grep -q "FFT PLACEHOLDER" "$FFT_BYPASS_SRC"; then
        echo "  [INFO]    fft256_dual_symbol_frontend.v is still the bypass stub."
        echo "            This is EXPECTED and CORRECT for P3-11 dry-run."
        echo "            The P3-11 test harness uses meyr_fft256_actual_integration_top"
        echo "            directly — it does NOT use fft256_dual_symbol_frontend."
    else
        echo "  [INFO]    fft256_dual_symbol_frontend.v: FFT PLACEHOLDER not found."
        echo "            This may mean the bypass stub was modified. Investigate before proceeding."
    fi
else
    echo "  [WARN]    $FFT_BYPASS_SRC not found — cannot check bypass status."
fi

# ---------------------------------------------------------------------------
# Final summary
# ---------------------------------------------------------------------------
echo ""
echo "=========================================="
if [[ "$BLOCKED" -eq 0 ]]; then
    echo "RESULT: ALL CHECKS PASSED"
    echo "  Ready to proceed with P3-12 simulation."
    echo "  Run: bash scripts/run_p3_11_real_fft_meyr_sim.sh"
else
    echo "RESULT: BLOCKED"
    echo ""
    echo "  One or more required files or tools are missing (see [BLOCKED] lines above)."
    echo "  Resolve all blockers before running simulation."
    echo ""
    echo "  Typical resolution order:"
    echo "    1. If P3-12 artifacts missing: run P3-12 session to create them"
    echo "    2. If sweep vectors missing: python3 scripts/gen_phase3_integer_cfo_sweep_vectors.py"
    echo "    3. If xsim/Vivado missing: install Vivado and source settings64.sh"
    echo "    4. If Xilinx IP missing: generate with 'create_ip' + 'generate_target' in Vivado"
    echo ""
    echo "  iverilog compile-only test (USE_BEHAVIORAL_STUB=1) may still be feasible."
    echo "  Accurate k_int simulation (USE_BEHAVIORAL_STUB=0) requires xsim + Xilinx IP."
fi
echo "=========================================="

exit "$BLOCKED"
