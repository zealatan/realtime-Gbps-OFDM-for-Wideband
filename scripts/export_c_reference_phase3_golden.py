#!/usr/bin/env python3
"""
export_c_reference_phase3_golden.py — Session D / P3-15A
Extract Phase 3 C reference observable values and write normalized JSON.

Sources consulted (in priority order):
  1. golden/phase3_golden_values.txt  — generated by scripts/golden_dump
  2. golden/phase3_iq_stimulus_meta.json — stimulus metadata
  3. Hard-coded fallback for known-stable values when files are missing

If scripts/golden_dump exists and is executable, re-runs it to regenerate the
golden values from the stored IQ stimulus.

Output:
  golden/session_D_p3_15a/c_reference_observables.json

Schema matches rtl_observables.json produced by normalize_rtl_phase3_outputs.py.
"""

import argparse
import json
import math
import os
import subprocess
import sys

# ---------------------------------------------------------------------------
# Paths (relative to repo root)
# ---------------------------------------------------------------------------
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SCRIPT_DIR)

GOLDEN_DUMP_BIN  = os.path.join(ROOT, "scripts", "golden_dump")
IQ_F32           = os.path.join(ROOT, "golden", "phase3_iq_stimulus.f32")
GOLDEN_VALUES    = os.path.join(ROOT, "golden", "phase3_golden_values.txt")
AUTOCORR_FULL    = os.path.join(ROOT, "golden", "phase3_autocorr_full.txt")
META_JSON        = os.path.join(ROOT, "golden", "phase3_iq_stimulus_meta.json")
OUT_DIR          = os.path.join(ROOT, "golden", "session_D_p3_15a")
OUT_JSON         = os.path.join(OUT_DIR, "c_reference_observables.json")

Q15_MAX = 32768.0


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def parse_kv(path):
    """Parse space-separated key-value file; skip # comments."""
    kv = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(None, 1)
            if len(parts) == 2:
                kv[parts[0]] = parts[1]
    return kv


def try_regen_golden(verbose):
    """Try to re-run golden_dump to regenerate golden values. Non-fatal."""
    if not os.path.isfile(IQ_F32):
        print(f"  [skip] IQ stimulus not found: {IQ_F32}")
        return False
    if not os.path.isfile(GOLDEN_DUMP_BIN):
        print(f"  [skip] golden_dump binary not found: {GOLDEN_DUMP_BIN}")
        return False
    if not os.access(GOLDEN_DUMP_BIN, os.X_OK):
        print(f"  [skip] golden_dump not executable: {GOLDEN_DUMP_BIN}")
        return False

    print(f"  Running golden_dump: {GOLDEN_DUMP_BIN}")
    try:
        result = subprocess.run(
            [GOLDEN_DUMP_BIN, IQ_F32, GOLDEN_VALUES, AUTOCORR_FULL],
            capture_output=True, text=True, timeout=30
        )
        if result.returncode != 0:
            print(f"  [warn] golden_dump exited {result.returncode}: {result.stderr.strip()}")
            return False
        if verbose:
            print(result.stdout.strip())
        print(f"  golden_dump OK → {GOLDEN_VALUES}")
        return True
    except Exception as e:
        print(f"  [warn] golden_dump failed: {e}")
        return False


def frac_cfo_expected_q15(offset_float):
    """Convert fractional CFO float offset to expected RTL Q1.15 word.
    RTL convention (verified Session A/12C): word = +offset * 2 * 32768.
    """
    return offset_float * 2.0 * Q15_MAX


def load_meta_json():
    """Load stimulus metadata JSON; return dict or {}."""
    if os.path.isfile(META_JSON):
        try:
            with open(META_JSON) as f:
                return json.load(f)
        except Exception as e:
            print(f"  [warn] Could not parse {META_JSON}: {e}")
    return {}


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description="Export C reference Phase3 observables to JSON")
    ap.add_argument("--regen", action="store_true",
                    help="Re-run golden_dump binary to regenerate golden_values.txt")
    ap.add_argument("--verbose", "-v", action="store_true")
    ap.add_argument("--out", default=OUT_JSON,
                    help=f"Output JSON path (default: {OUT_JSON})")
    args = ap.parse_args()

    os.makedirs(OUT_DIR, exist_ok=True)

    print("=" * 64)
    print("Session D / P3-15A — C Reference Export")
    print("=" * 64)

    # -----------------------------------------------------------------------
    # Step 1: (optionally) re-generate golden values
    # -----------------------------------------------------------------------
    regen_ok = False
    if args.regen:
        print("\n[1] Re-generating golden values via golden_dump...")
        regen_ok = try_regen_golden(args.verbose)
    else:
        print(f"\n[1] Using existing golden values (pass --regen to refresh)")

    # -----------------------------------------------------------------------
    # Step 2: Parse golden_values.txt
    # -----------------------------------------------------------------------
    print(f"\n[2] Parsing: {GOLDEN_VALUES}")
    gv = {}
    golden_available = False
    if os.path.isfile(GOLDEN_VALUES):
        gv = parse_kv(GOLDEN_VALUES)
        golden_available = True
        print(f"  Keys found: {list(gv.keys())}")
    else:
        print(f"  [warn] File not found: {GOLDEN_VALUES}")
        print(f"  Suggestion: rebuild golden_dump.c and run:")
        print(f"    gcc -O2 -Wall scripts/golden_dump.c -lm -o scripts/golden_dump")
        print(f"    ./scripts/golden_dump golden/phase3_iq_stimulus.f32 \\")
        print(f"        golden/phase3_golden_values.txt golden/phase3_autocorr_full.txt")

    # -----------------------------------------------------------------------
    # Step 3: Parse stimulus metadata
    # -----------------------------------------------------------------------
    print(f"\n[3] Parsing: {META_JSON}")
    meta = load_meta_json()
    if meta:
        print(f"  Keys found: {list(meta.keys())}")
    else:
        print(f"  [warn] Not found or unparseable — using defaults")

    # -----------------------------------------------------------------------
    # Step 4: Build normalized observables
    # -----------------------------------------------------------------------
    print("\n[4] Building normalized observables...")

    def gv_int(key, fallback=None):
        if key in gv:
            try:
                return int(gv[key])
            except ValueError:
                pass
        return fallback

    def gv_float(key, fallback=None):
        if key in gv:
            try:
                return float(gv[key])
            except ValueError:
                pass
        return fallback

    def meta_get(key, fallback=None):
        return meta.get(key, fallback)

    # Frame detection
    det_status   = gv_int("DETECTION_STATUS", None)
    frame_found  = bool(det_status) if det_status is not None else None
    frame_index  = gv_int("FRAME_START", meta_get("expected_frame_start", None))
    peak_lag     = gv_int("PEAK_INDEX_AUTO", meta_get("expected_peak_index_auto", None))
    slot_start   = gv_int("SLOT_START_INDEX", meta_get("expected_slot_start_approx", None))

    # Fractional CFO
    frac_offset  = gv_float("FRAC_CFO_OFFSET", meta_get("expected_frac_cfo_offset", None))
    frac_valid   = (frac_offset is not None)
    frac_q15_exp = round(frac_cfo_expected_q15(frac_offset)) if frac_offset is not None else None

    # PSS/SSS constants
    pss_start    = gv_int("PSS_START", 32)
    sss_start    = gv_int("SSS_START", 320)
    pss_cnt      = gv_int("PSS_SAMPLE_COUNT", 256)
    sss_cnt      = gv_int("SSS_SAMPLE_COUNT", 256)

    # Integer CFO (Meyr estimator — no FFT in golden_dump, values are known-good stubs)
    meyr_peak    = gv_int("MEYR_PEAK_INDEX", None)
    int_cfo_word = gv_int("INTEGER_CFO_WORD", None)  # in subcarrier bins
    int_cfo_valid= (meyr_peak is not None)

    # -----------------------------------------------------------------------
    # Populate JSON
    # -----------------------------------------------------------------------
    out = {
        "_meta": {
            "session": "D / P3-15A",
            "source": "C reference (golden_dump.c + gen_phase3_iq_stimulus.py)",
            "generated_by": "scripts/export_c_reference_phase3_golden.py",
            "golden_values_file": GOLDEN_VALUES,
            "golden_available": golden_available,
            "regen_ran": args.regen,
            "regen_ok": regen_ok,
            "stimulus": os.path.relpath(IQ_F32, ROOT),
            "notes": [
                "frame_found/frame_index/peak_lag/slot_start_index: C algorithm (Steps 1-3)",
                "frac_cfo_offset_float: CP autocorr phase angle (Step 2); +0.05 = +eps_frac shift",
                "frac_cfo_word_q15_expected: derived as round(offset * 2 * 32768); RTL same-sign convention",
                "int_cfo_index/int_cfo_est_bins: Meyr peak / integer bins (Step 4 stub for zero-CFO stimulus)",
                "int_cfo_applied: null — C reference does not apply NCO correction",
                "m_axis: BLOCKED — golden_dump.c does not produce corrected output samples"
            ]
        },
        "frame_found":      frame_found,
        "frame_index":      frame_index,
        "peak_lag":         peak_lag,
        "slot_start_index": slot_start,
        "frac_cfo_valid":   frac_valid,
        "frac_cfo_offset_float":       frac_offset,
        "frac_cfo_word_q15_expected":  frac_q15_exp,
        "frac_cfo_word_q15_tolerance": 2,
        "frac_cfo_word_q15_rel_tol":   0.01,
        "int_cfo_valid":    int_cfo_valid,
        "int_cfo_index":    meyr_peak,
        "int_cfo_index_tolerance": 1,
        "int_cfo_est_bins": int_cfo_word,
        "int_cfo_word_nco": None,
        "_int_cfo_word_nco_status": "unavailable — C golden_dump reports bins, not NCO step word",
        "int_cfo_applied":  None,
        "_int_cfo_applied_status": "unavailable — RTL-only observable",
        "pss_start_offset": pss_start,
        "sss_start_offset": sss_start,
        "pss_sample_count": pss_cnt,
        "sss_sample_count": sss_cnt,
        "m_axis": {
            "available": False,
            "_status": "STAGE4_BLOCKED_M_AXIS_GOLDEN_UNAVAILABLE — golden_dump.c does not produce NCO-corrected output; blocked pending Session C golden provision",
            "length":       None,
            "tlast_index":  None,
            "iq_file":      None
        }
    }

    # -----------------------------------------------------------------------
    # Step 5: Write JSON
    # -----------------------------------------------------------------------
    with open(args.out, "w") as f:
        json.dump(out, f, indent=2)
    print(f"\n[5] Written: {args.out}")

    # -----------------------------------------------------------------------
    # Step 6: Validation summary
    # -----------------------------------------------------------------------
    print("\n[6] Observable summary:")
    required = [
        ("frame_found",      out["frame_found"]),
        ("frame_index",      out["frame_index"]),
        ("peak_lag",         out["peak_lag"]),
        ("slot_start_index", out["slot_start_index"]),
        ("frac_cfo_valid",   out["frac_cfo_valid"]),
        ("frac_cfo_offset",  out["frac_cfo_offset_float"]),
        ("frac_cfo_q15_exp", out["frac_cfo_word_q15_expected"]),
        ("int_cfo_valid",    out["int_cfo_valid"]),
        ("int_cfo_index",    out["int_cfo_index"]),
        ("int_cfo_est_bins", out["int_cfo_est_bins"]),
    ]
    n_missing = 0
    for name, val in required:
        status = "OK" if val is not None else "MISSING"
        if val is None:
            n_missing += 1
        print(f"  {status:7s}  {name} = {val}")

    print(f"\n  m_axis: BLOCKED (C reference does not produce M_AXIS)")
    print(f"\n  Missing required fields: {n_missing}")

    if n_missing == 0:
        print("\nC_REFERENCE_EXPORT: PASS (all required fields available)")
        return 0
    else:
        print(f"\nC_REFERENCE_EXPORT: PARTIAL ({n_missing} fields unavailable)")
        print("  Rebuild golden_dump from scripts/golden_dump.c and re-run with --regen")
        return 1


if __name__ == "__main__":
    sys.exit(main())
