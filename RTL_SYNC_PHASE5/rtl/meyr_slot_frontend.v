`timescale 1ns/1ps
// =============================================================
//  meyr_slot_frontend.v
//
//  Pipelined Slot Demux for OFDM Receiver Front-End
//
//  PURPOSE:
//    Sits between ADC/timing-sync and meyr_cfo_top.
//    Accepts raw continuous sample stream + slot_start pulse,
//    strips CPs, routes PSS/SSS to Meyr estimator.
//
//  SLOT STRUCTURE (from OFDM.h):
//    NUM_SYN  = 2 (PSS, SSS)
//    NUM_DATA = 12 (data symbols, 5G NR: 14 total - 2 sync)
//    Each symbol = CP_LEN + N samples
//    Total slot  = (NUM_SYN + NUM_DATA) * (CP_LEN + N)
//
//    [CP+PSS][CP+SSS][CP+D0][CP+D1]...[CP+D11]
//     sym 0   sym 1   sym 2  sym 3     sym 13
//
//  OPERATION:
//    1. Wait for slot_start pulse from timing sync
//    2. Count through entire slot
//    3. During CP regions: suppress output (tvalid=0)
//    4. During PSS/SSS payload: assert meyr_tvalid
//    5. During data payload: assert data_tvalid
//
//  ARCHITECTURE:
//    Pure counter logic. No FSM, no BRAM, no buffering.
//    1-cycle registered pipeline for clean timing.
//
//  INTERFACE WITH Fractional CFO BLOCK:
//    slot_start is a single-cycle pulse indicating sample 0
//    of a new slot has arrived on s_tdata in this cycle.
//    Typically generated by CP autocorrelation peak detector
//    (Van de Beek method).
// =============================================================
module meyr_slot_frontend #(
    parameter N             = 256,
    parameter CP_LEN        = 32,
    parameter NUM_SYN       = 2,
    // ISS-27/08: TX slot = 2 sync + 12 data symbols (pluto.h NUM_DATA_BLOCKS=12).
    parameter NUM_DATA      = 12
)(
    input  wire        clk,
    input  wire        rst_n,

    // ---- Upstream: raw ADC stream ----
    input  wire [31:0] s_tdata,
    input  wire        s_tvalid,
    input  wire        slot_start,   // pulse from timing sync

    // ---- Output to meyr_cfo_top (via meyr_sync_capture): clean PSS + SSS ----
    output reg  [31:0] meyr_tdata,
    output reg         meyr_tvalid,
    // One-cycle pulse marking the first PSS payload beat of the slot.
    // Sampled by meyr_sync_capture to start its 2N capture window.
    output reg         pss_first_beat,
    output reg         sss_first_beat,   // mirror of pss_first_beat for the SSS
                                         // payload — lets sync_capture re-pin the
                                         // SSS window (immune to beat-count drift)
    input  wire        meyr_tready,  // from meyr_cfo_top / sync_capture

    // ---- Output for data symbols (to demodulator) ----
    output reg  [31:0] data_tdata,
    output reg         data_tvalid,
    output reg  [3:0]  data_sym_idx  // which data symbol (0..NUM_DATA-1)
);

    // meyr_tready is a back-pressure signal from sync_capture. The
    // current implementation uses the buffer's always-accept policy
    // and asserts payload beats unconditionally; meyr_tready is left
    // as an interface contract for future ping-pong work.
    wire _unused_meyr_tready = meyr_tready;

    // ---------------------------------------------------------
    // Slot Geometry (all derived from parameters)
    // ---------------------------------------------------------
    localparam SYM_LEN     = CP_LEN + N;
    localparam TOTAL_SYMS  = NUM_SYN + NUM_DATA;
    localparam SLOT_LEN    = TOTAL_SYMS * SYM_LEN;

    // ---------------------------------------------------------
    // Counters
    // ---------------------------------------------------------
    reg [$clog2(SLOT_LEN)-1:0] slot_cnt;    // 0..SLOT_LEN-1
    reg                        active;       // currently inside a slot

    // Derived from slot_cnt (combinational)
    wire [$clog2(TOTAL_SYMS)-1:0] sym_num;   // which symbol (0-7)
    wire [$clog2(SYM_LEN)-1:0]    sym_phase; // position within symbol

    assign sym_num   = slot_cnt / SYM_LEN;
    assign sym_phase = slot_cnt % SYM_LEN;
    // Using division/modulo is fine for combinational decode -
    // Vivado synthesizes this as a comparator tree, not a divider,
    // because SYM_LEN is a power-of-two-friendly constant.
    // For non-power-of-two SYM_LEN, replace with counter-based tracking.

    // Phase decode
    wire is_cp      = (sym_phase < CP_LEN);
    wire is_payload = !is_cp;

    // Symbol type decode
    wire is_pss     = (sym_num == 0);
    wire is_sss     = (sym_num == 1);
    wire is_sync    = is_pss | is_sss;
    wire is_data    = (sym_num >= NUM_SYN);

    // ---------------------------------------------------------
    // Slot Counter
    // ---------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            slot_cnt <= 0;
            active   <= 0;
        end else begin
            if (slot_start && s_tvalid) begin
                // New slot begins - reset counter
                active   <= 1;
                slot_cnt <= 1;  // slot_start coincides with sample 0, so next is 1
            end else if (active && s_tvalid) begin
                if (slot_cnt == SLOT_LEN - 1) begin
                    //active   <= 0; //NOT set active <= 0 here. Let the counter wrap natively, or let the next slot_start handle it.
                    slot_cnt <= 0;
                end else begin
                    slot_cnt <= slot_cnt + 1;
                end
            end
        end
    end

    // ---------------------------------------------------------
    // Output Registers (1-cycle pipeline)
    // ---------------------------------------------------------
    // pss_first_beat fires on the first PSS payload beat of a slot —
    // i.e. when sym_num==0 (PSS) and sym_phase==CP_LEN (first payload
    // sample), gated on active & s_tvalid. Single-cycle pulse.
    wire is_first_pss_beat = active && s_tvalid && is_pss && (sym_phase == CP_LEN);
    // First SSS payload beat — same condition for sym_num==1 (SSS).
    wire is_first_sss_beat = active && s_tvalid && is_sss && (sym_phase == CP_LEN);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            meyr_tdata     <= 32'h0;
            meyr_tvalid    <= 1'b0;
            pss_first_beat <= 1'b0;
            sss_first_beat <= 1'b0;
            data_tdata     <= 32'h0;
            data_tvalid    <= 1'b0;
            data_sym_idx   <= 4'd0;
        end else begin
            // Defaults: no output
            meyr_tvalid    <= 1'b0;
            pss_first_beat <= 1'b0;
            sss_first_beat <= 1'b0;
            data_tvalid    <= 1'b0;

            if (active && s_tvalid && is_payload) begin
                if (is_sync) begin
                    // PSS or SSS payload → route to Meyr
                    meyr_tdata  <= s_tdata;
                    meyr_tvalid <= 1'b1;
                    if (is_first_pss_beat) pss_first_beat <= 1'b1;
                    if (is_first_sss_beat) sss_first_beat <= 1'b1;
                end else if (is_data) begin
                    // Data symbol payload → route to demodulator
                    data_tdata   <= s_tdata;
                    data_tvalid  <= 1'b1;
                    data_sym_idx <= sym_num - NUM_SYN;
                end
            end

            // Handle slot_start on the very first sample
            if (slot_start && s_tvalid) begin
                // Sample 0 is CP of PSS - suppress both outputs
                meyr_tvalid    <= 1'b0;
                pss_first_beat <= 1'b0;
                sss_first_beat <= 1'b0;
                data_tvalid    <= 1'b0;
            end
        end
    end

endmodule