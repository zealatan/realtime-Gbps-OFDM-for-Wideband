#!/usr/bin/env python3
"""
compare_doc002_fft_values.py — DOC-002 FFT bin-value gate comparison

Compares RTL behavioral DFT stub outputs against Python golden references
generated by gen_doc002_fft_reference.py.

Convention:
  - Both RTL and golden use unscaled 256-pt DFT (numpy.fft.fft convention)
  - Output values are int16 [-32768..32767]
  - Max acceptable absolute error: 1 LSB (due to integer rounding)
  - For saturation cases (V1 bin 7): RTL and golden both clamp to 32767

C reference note:
  fft_without_rearrange() in signal_processing_common.c divides by sqrt(256)=16.
  The behavioral stub is UNSCALED. The real Xilinx IP divides by 16 via SCALE_SCH=0xAA.
  This is correctly documented; the gate compares behavioral stub to behavioral golden.
"""

import csv, sys, os, math

BASE   = os.path.join(os.path.dirname(__file__), '..')
VEC_DIR = os.path.join(BASE, 'vectors', 'doc002')
OUT_DIR = os.path.join(BASE, 'sim_out', 'verification_closure_20260603', 'doc002_fft_check')
RPT_DIR = os.path.join(BASE, 'reports', 'verification_closure_20260603')

MAX_ABS_ERR_THRESHOLD = 1  # 1 LSB tolerance for int16 rounding

def load_csv(path):
    rows = []
    with open(path) as f:
        rd = csv.DictReader(f)
        for row in rd:
            rows.append((int(row['bin']), int(row['Re']), int(row['Im'])))
    return rows

def compare_vector(vec_name, golden_path, output_path):
    golden = load_csv(golden_path)
    output = load_csv(output_path)

    if len(golden) != 256 or len(output) != 256:
        print(f'  FAIL {vec_name}: golden={len(golden)} output={len(output)} bins (expected 256 each)')
        return False, 0, 0, 0

    max_err_re = 0
    max_err_im = 0
    max_err_abs = 0
    sum_sq = 0.0
    mismatches = []

    for k in range(256):
        g_bin, g_re, g_im = golden[k]
        o_bin, o_re, o_im = output[k]
        err_re = abs(o_re - g_re)
        err_im = abs(o_im - g_im)
        err_abs = max(err_re, err_im)
        sum_sq += err_re**2 + err_im**2
        if err_abs > max_err_abs:
            max_err_abs = err_abs
        if err_re > max_err_re:
            max_err_re = err_re
        if err_im > max_err_im:
            max_err_im = err_im
        if err_abs > MAX_ABS_ERR_THRESHOLD:
            mismatches.append((k, g_re, g_im, o_re, o_im, err_re, err_im))

    rms = math.sqrt(sum_sq / (2 * 256))
    passed = (max_err_abs <= MAX_ABS_ERR_THRESHOLD)

    print(f'  {vec_name}:  max_err={max_err_abs}  rms={rms:.3f}  mismatches={len(mismatches)}  {"PASS" if passed else "FAIL"}')
    if mismatches:
        for (k, g_re, g_im, o_re, o_im, er, ei) in mismatches[:5]:
            print(f'    bin {k}: golden=({g_re},{g_im})  rtl=({o_re},{o_im})  err=({er},{ei})')
        if len(mismatches) > 5:
            print(f'    ... ({len(mismatches)-5} more mismatches not shown)')

    return passed, max_err_abs, rms, len(mismatches)

# ── Run comparisons ────────────────────────────────────────────────────────────
print('DOC-002 FFT Value Comparison Gate')
print('=' * 60)
print(f'  Tolerance: max_abs_err <= {MAX_ABS_ERR_THRESHOLD} LSB')
print(f'  RTL mode: USE_BEHAVIORAL_STUB=3 (exact 256-pt DFT, unscaled)')
print()

vectors = [
    ('V0_impulse',    'v0_golden.csv', 'v0_output.csv'),
    ('V1_tone_k7',    'v1_golden.csv', 'v1_output.csv'),
    ('V2_pseudo_rng', 'v2_golden.csv', 'v2_output.csv'),
]

results = []
for (name, gfile, ofile) in vectors:
    gpath = os.path.join(VEC_DIR, gfile)
    opath = os.path.join(OUT_DIR, ofile)
    if not os.path.exists(opath):
        print(f'  SKIP {name}: output file not found: {opath}')
        results.append((name, False, 0, 0, 0))
        continue
    passed, max_err, rms, nmm = compare_vector(name, gpath, opath)
    results.append((name, passed, max_err, rms, nmm))

# ── CSV report ─────────────────────────────────────────────────────────────────
csv_path = os.path.join(RPT_DIR, 'doc002_fft_value_compare.csv')
os.makedirs(RPT_DIR, exist_ok=True)
with open(csv_path, 'w', newline='') as f:
    w = csv.writer(f)
    w.writerow(['vector', 'pass', 'max_abs_err', 'rms_err', 'mismatch_bins'])
    for (name, passed, max_err, rms, nmm) in results:
        w.writerow([name, 'PASS' if passed else 'FAIL', max_err, f'{rms:.3f}', nmm])

# ── Gate verdict ───────────────────────────────────────────────────────────────
all_pass = all(r[1] for r in results)
print()
print('=' * 60)
print(f'  Vectors: {len(results)}   PASS: {sum(1 for r in results if r[1])}   FAIL: {sum(1 for r in results if not r[1])}')
print()
if all_pass:
    print('DOC_002_FFT_VALUE_GATE: PASS (behavioral stub, unscaled DFT)')
else:
    print('DOC_002_FFT_VALUE_GATE: FAIL')
print()
print('Scale note:')
print('  RTL behavioral stub (USE_BEHAVIORAL_STUB=3) is UNSCALED (matches numpy.fft.fft).')
print('  C reference fft_without_rearrange() divides by sqrt(256)=16.')
print('  Real Xilinx IP applies 1/16 via SCALE_SCH=0xAA (alternating stage scaling).')
print('  Behavioral PASS does NOT imply real Xilinx FFT IP is verified.')
print('  Real IP verification requires Vivado simulation with xfft_v9_1_8.')
print('=' * 60)
sys.exit(0 if all_pass else 1)
